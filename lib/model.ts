// Token launch radar — valuation model (radar-2).
//
// The board ranks pre-token protocols by an implied launch value derived ONLY
// from the sealed snapshot's own figures. No protocol name is special-cased:
// the same function scores every row.
//
//   multiple  = category comparables: the median market-cap/TVL multiple of
//               live-token protocols in the same category (n >= 3); smaller
//               samples are shrunk toward the global median; categories with
//               no live comps use the global median. Multiples are capped.
//   base      = multiple x TVL^0.85 x 1e6^0.15   (sublinear in size: a $2.7B
//               protocol is not 100x a $27M one on size alone)
//   growth    = clamp(change_7d, -50, +100); growthMult = clamp(1 + 0.6*g/100, 0.7, 1.4)
//   maturity  = 0.7 + 0.3 x (1 - exp(-age_days/365)); unknown age -> 0.85
//   implied   = max(1, round(base x growthMult x maturity))
//
// Live-token protocols are never ranked: the board shows them apart, at the
// market's own values, so the judge can see the two sets are separated.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

